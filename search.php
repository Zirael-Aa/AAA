/**
 * Нормализация строки: нижний регистр, ё→е, убираем лишние пробелы.
 */
function norm(string $s): string {
    $s = mb_strtolower($s, 'UTF-8');
    $s = str_replace('ё', 'е', $s);
    return trim(preg_replace('/\s+/u', ' ', $s));
}

$q = norm(trim($_GET['q'] ?? ''));

if ($q === '' || mb_strlen($q, 'UTF-8') < 2) {
    echo json_encode([
        'ok'      => false,
        'error'   => 'Введите минимум 2 символа',
        'results' => [],
    ], JSON_UNESCAPED_UNICODE);
    exit;
}

$results = [];

foreach ($pages as $p) {
    $haystack = norm($p['title'] . ' ' . $p['desc'] . ' ' . $p['keywords']);

    // Ищем вхождение запроса в haystack
    $pos = mb_strpos($haystack, $q, 0, 'UTF-8');
    if ($pos === false) continue;

    // Считаем "вес" совпадения: чем раньше и полнее — тем выше
    $score = 0;
    if (mb_strpos(norm($p['title']), $q, 0, 'UTF-8') !== false) $score += 100;
    if (mb_strpos(norm($p['keywords']), $q, 0, 'UTF-8') !== false) $score += 50;
    if (mb_strpos(norm($p['desc']), $q, 0, 'UTF-8') !== false) $score += 20;

    $results[] = [
        'url'    => $p['url'],
        'title'  => $p['title'],
        'desc'   => $p['desc'],
        'score'  => $score,
    ];
}

// Сортировка по релевантности (убывание)
usort($results, fn($a, $b) => $b['score'] <=> $a['score']);

// Убираем служебное поле score из ответа
foreach ($results as &$r) unset($r['score']);
unset($r);

echo json_encode([
    'ok'      => true,
    'query'   => $q,
    'count'   => count($results),
    'results' => $results,
], JSON_UNESCAPED_UNICODE);